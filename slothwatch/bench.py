"""Ladder vs naive baseline (every row sent to the same local model).
Honesty rules baked in: tokens are MEASURED when Ollama answers, ESTIMATED (chars/4) otherwise, and every
number is labelled with which. Baseline detection is only reported when a live model produced it.
Closed-API cost is an ESTIMATE from configurable per-token prices. Misses are reported, not hidden."""
from __future__ import annotations
import json, tempfile, time
from datetime import date
from pathlib import Path
from .config import Config
from .demo import generator as g
from .llm import Explainer, estimate_tokens, load_prompt
from .normalize import clean_merchant
from .runner import Engine
from .trace import NullTracer


def compare_scenario(name: str, seed: int = 7, cfg: Config | None = None) -> dict:
    cfg = cfg or Config(data_dir=tempfile.mkdtemp(prefix="sloth-bench-"), learning=False, desktop_notify=False)
    ex = Explainer(cfg)
    live = ex.ollama.available()
    rows = g.load_rows(name, seed)
    eng = Engine(cfg, tracer=NullTracer(), explainer=ex)
    t0 = time.perf_counter()
    res = eng.run(rows, g.SCEN_START, g.SCEN_END, mode="bench")
    ladder_wall = time.perf_counter() - t0
    c = res["counts"]

    cur = [t for t in rows if g.SCEN_START <= t.date <= g.SCEN_END]
    tpl = load_prompt("baseline_v1.txt")
    b_in = b_out = 0
    b_flag: set[str] = set()
    t1 = time.perf_counter()
    for tx in cur:
        prior = [o.amount for o in rows if o.merchant == tx.merchant and o.seq < tx.seq][-6:]
        prompt = tpl.format(merchant=tx.merchant, date=tx.date, amount=f"{cfg.currency}{tx.amount:.2f}", recent=prior)
        if live:
            try:
                text, a, b = ex.ollama.generate(prompt)
                b_in, b_out = b_in + a, b_out + b
                if json.loads(text).get("suspicious") is True:
                    b_flag.add(tx.merchant)
            except Exception:
                b_in, b_out = b_in + estimate_tokens(prompt), b_out + 30
        else:
            b_in, b_out = b_in + estimate_tokens(prompt), b_out + 30
    b_wall = (time.perf_counter() - t1) if live else None

    planted = {clean_merchant(p["merchant"]) for p in g.planted(name)}
    rows_flagged = res["surprise_rows"]
    flagged = {m for m, _, _ in rows_flagged}
    tp = len(planted & flagged)
    def cost(i, o):
        return (i * cfg.price_in_per_m + o * cfg.price_out_per_m) / 1e6
    return {"scenario": name, "mode": "live-gemma" if live else "offline-template (token counts estimated)",
            "rows": c["rows"], "rung0": c["rung0"], "rung1": c["rung1"], "surprises": c["surprises_total"],
            "ladder_gemma_wakeups": c["gemma_wakeups"], "baseline_llm_calls": len(cur),
            "ladder_tokens": c["tokens_in"] + c["tokens_out"], "baseline_tokens": b_in + b_out,
            "ladder_wall_s": round(ladder_wall, 3), "baseline_wall_s": None if b_wall is None else round(b_wall, 2),
            "est_cost_if_billed_ladder_usd": round(cost(c["tokens_in"], c["tokens_out"]), 5),
            "est_cost_if_billed_baseline_usd": round(cost(b_in, b_out), 5),
            "planted": len(planted), "caught": tp, "false_positive_rows": sum(1 for m, _, _ in rows_flagged if m not in planted),
            "recall": None if not planted else round(tp / len(planted), 2),
            "precision": None if not rows_flagged else round(sum(1 for m, _, _ in rows_flagged if m in planted) / len(rows_flagged), 2),
            "baseline_flagged_planted": (len(planted & b_flag) if live else None),
            "baseline_false_positives": (len(b_flag - planted) if live else None),
            "sloth_score": c["rows"] - c["gemma_wakeups"],
            "methods": res["methods"]}


def run_all(out_dir: str | Path = "benchmarks/results", seed: int = 7) -> list[dict]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    results = [compare_scenario(n, seed) for n in g.SCENARIOS]
    (out / "benchmark.json").write_text(json.dumps(results, indent=1))
    mode = results[0]["mode"]
    L = [f"# SlothWatch benchmark\n\nMode: **{mode}**. Seed {seed}. Generated by `slothwatch bench`; every number below came from this run.\n",
         "Sloth Score = rows that did NOT wake the LLM. Baseline = naive 'send every row to the LLM'.",
         "Costs are ESTIMATES: the same token counts billed at an assumed closed-API price (see `price_*` in config). "
         "Local inference itself cost $0.\n",
         "| Scenario | Rows | Settled by rules | Settled by forecast | Gemma wake-ups (ladder) | LLM calls (baseline) | Sloth Score | Tokens ladder / baseline | Recall | Precision | False-positive rows |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in results:
        L.append(f"| {r['scenario']} | {r['rows']} | {r['rung0']} | {r['rung1']} | {r['ladder_gemma_wakeups']} | "
                 f"{r['baseline_llm_calls']} | {r['sloth_score']} | {r['ladder_tokens']} / {r['baseline_tokens']} | "
                 f"{'n/a' if r['recall'] is None else r['recall']} | {'n/a' if r['precision'] is None else r['precision']} | {r['false_positive_rows']} |")
    tot_w = sum(r["ladder_gemma_wakeups"] for r in results); tot_b = sum(r["baseline_llm_calls"] for r in results)
    L += ["", f"Across all scenarios the ladder woke the model **{tot_w}** times versus **{tot_b}** for the baseline "
              f"({100 * (1 - tot_w / tot_b):.1f}% fewer).", ""]
    if results[0]["baseline_flagged_planted"] is None:
        L.append("> Baseline detection quality and baseline wall time are **not measured** in this run because no live "
                 "Ollama model was available. Re-run with Ollama up (`slothwatch doctor`) to fill those in.")
    else:
        L.append("| Scenario | Baseline caught planted | Baseline false positives | Baseline wall (s) | Ladder wall (s) |\n|---|---|---|---|---|")
        for r in results:
            L.append(f"| {r['scenario']} | {r['baseline_flagged_planted']}/{r['planted']} | {r['baseline_false_positives']} | {r['baseline_wall_s']} | {r['ladder_wall_s']} |")
    misses = [r for r in results if r["recall"] is not None and r["recall"] < 1]
    L.append("\n**Misses:** " + ("; ".join(f"{r['scenario']} caught {r['caught']}/{r['planted']}" for r in misses) if misses else "none on these scenarios (synthetic data; real data will be messier)."))
    (out / "report.md").write_text("\n".join(L) + "\n")
    (out / "chart.svg").write_text(_chart(results))
    return results


def _chart(results) -> str:
    W, H, pad = 720, 340, 50
    mx = max(r["baseline_llm_calls"] for r in results)
    bw = (W - 2 * pad) / len(results)
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" font-family="sans-serif" font-size="11"><rect width="{W}" height="{H}" fill="white"/>',
             f'<text x="{pad}" y="22" font-size="14" font-weight="bold">LLM wake-ups per scenario: ladder vs naive baseline</text>']
    for i, r in enumerate(results):
        x = pad + i * bw
        hb, hl = r["baseline_llm_calls"] / mx * (H - 2 * pad - 20), r["ladder_gemma_wakeups"] / mx * (H - 2 * pad - 20)
        parts += [f'<rect x="{x+6:.0f}" y="{H-pad-hb:.0f}" width="{bw/2-8:.0f}" height="{hb:.0f}" fill="#c0392b"/>',
                  f'<rect x="{x+bw/2:.0f}" y="{H-pad-hl:.0f}" width="{bw/2-8:.0f}" height="{max(hl,1):.0f}" fill="#27ae60"/>',
                  f'<text x="{x+6:.0f}" y="{H-pad-hb-4:.0f}">{r["baseline_llm_calls"]}</text><text x="{x+bw/2:.0f}" y="{H-pad-hl-4:.0f}">{r["ladder_gemma_wakeups"]}</text>',
                  f'<text x="{x+4:.0f}" y="{H-pad+14}" font-size="9">{r["scenario"]}</text>']
    parts += [f'<text x="{W-170}" y="40" fill="#c0392b">naive baseline</text><text x="{W-170}" y="56" fill="#27ae60">SlothWatch ladder</text></svg>']
    return "".join(parts)
